/* 달 이름을 바르게 읽어 주는지 확인합니다.  node 검증/달읽기검증.js
   기계 음성은 9がつ 를 きゅうがつ 로 읽습니다. 소리 낼 때만 바른 읽기로 바꿉니다. */
const fs = require('fs'), path = require('path');
const 글 = fs.readFileSync(path.join(__dirname, '..', 'index.html'), 'utf8');

let 통과 = 0, 실패 = 0;
function 확인(이름, 참) { 참 ? (통과++, console.log('  ok   ' + 이름)) : (실패++, console.log('  FAIL ' + 이름)); }

const 시작 = 글.indexOf('const 달읽기 = [');
const 끝 = 글.indexOf('function speak(', 시작);
const 조각 = 시작 === -1 || 끝 === -1 ? null : [글.slice(시작, 끝)];
확인('읽을모양() 함수가 있다', !!조각);
const 읽을모양 = new Function(조각[0] + '\nreturn 읽을모양;')();

console.log('\n기계가 자주 틀리는 달');
확인('9월 → くがつ',  읽을모양('きょうは 9がつ です。') === 'きょうは くがつ です。');
확인('4월 → しがつ',  읽을모양('4がつ') === 'しがつ');
확인('7월 → しちがつ', 읽을모양('7がつ') === 'しちがつ');

console.log('\n나머지 달도 맞는가');
const 바름 = ['いちがつ','にがつ','さんがつ','しがつ','ごがつ','ろくがつ',
              'しちがつ','はちがつ','くがつ','じゅうがつ','じゅういちがつ','じゅうにがつ'];
확인('1월부터 12월까지 모두', 바름.every((바른, i) => 읽을모양((i + 1) + 'がつ') === 바른));
확인('한자 月 로 적혀 있어도 읽는다', 읽을모양('9月') === 'くがつ');

console.log('\n건드리면 안 되는 것');
확인('달이 아닌 숫자는 그대로', 읽을모양('9にち') === '9にち');
확인('13월 같은 것은 그대로', 읽을모양('13がつ') === '13がつ');
확인('0월도 그대로', 읽을모양('0がつ') === '0がつ');
확인('숫자가 없으면 그대로', 읽을모양('がつ') === 'がつ');
확인('빈 값도 견딘다', 읽을모양('') === '' && 읽을모양(null) === '' && 읽을모양(undefined) === '');
확인('일본어 문장은 그대로', 읽을모양('ももたろうです。') === 'ももたろうです。');

console.log('\n한 문장에 여러 달');
확인('여러 개를 모두 바꾼다', 읽을모양('4がつと 9がつ') === 'しがつと くがつ');

console.log('\n소리 낼 때만 바뀌는가');
확인('speak 이 읽을모양을 거친다', /new SpeechSynthesisUtterance\(읽을모양\(text\)\)/.test(글));
확인('화면 글자는 그대로 둔다 (달력은 9がつ 로 보임)', /\$\{m\+1\}がつ/.test(글));

console.log('\n통과 ' + 통과 + ' / 실패 ' + 실패);
process.exit(실패 ? 1 : 0);
